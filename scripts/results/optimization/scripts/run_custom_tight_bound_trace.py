from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

import yaml


def _tok(x: float) -> str:
    return f"{x:.3f}".rstrip("0").rstrip(".").replace(".", "p")


def _abs(path_str: str) -> Path:
    return Path(path_str).resolve()


def _run(cmd: list[str]) -> None:
    print("[run_custom_tight_bound_trace] $", " ".join(cmd))
    subprocess.run(cmd, check=True)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Run retained default + one custom tight-frequency bound and export replay trace panel."
    )
    parser.add_argument("--delta-f", type=float, required=True, help="Absolute |Delta f_COI| bound in Hz (e.g., 0.45).")
    parser.add_argument("--rocof", type=float, default=None, help="Absolute |RoCoF_COI| bound in Hz/s (defaults to --delta-f).")
    parser.add_argument("--base-scale", type=float, default=0.5, help="Scenario base loading scale.")
    parser.add_argument("--step-scale", type=float, default=1.4, help="Load-step scale.")
    parser.add_argument("--scenario-id", default=None, help="Optional explicit scenario id. Default uses base/step scales.")
    parser.add_argument("--results-root", default="results/thesis_optimization_results/results/tight_frequency_custom")
    parser.add_argument(
        "--generated-dir",
        default="results/thesis_optimization_results/configs/generated",
    )
    parser.add_argument("--log-tail-lines", type=int, default=120)
    parser.add_argument(
        "--allow-infeasible-replay",
        action="store_true",
        help="Allow replay export even when the custom optimization run is not optimal.",
    )
    args = parser.parse_args()

    delta_f = float(args.delta_f)
    rocof = float(args.rocof if args.rocof is not None else args.delta_f)
    if delta_f <= 0 or rocof <= 0:
        raise ValueError("Both bounds must be positive.")

    scenario_id = args.scenario_id or f"global_b{_tok(args.base_scale)}_s{_tok(args.step_scale)}"
    case_id = f"retained_df{_tok(delta_f)}_rocof{_tok(rocof)}"
    out_name = f"{scenario_id}__{case_id}"

    root = Path.cwd()
    generated_dir = _abs(args.generated_dir)
    generated_dir.mkdir(parents=True, exist_ok=True)

    results_root = _abs(args.results_root)
    suite_summary_json = results_root / f"{out_name}_summary.json"
    suite_summary_csv = results_root / f"{out_name}_summary.csv"
    suite_summary_md = results_root / f"{out_name}_summary.md"
    replay_outdir = _abs(f"results/thesis_optimization_results/local_validation/replay_trace_{out_name}")
    replay_config = generated_dir / f"replay_trace_{out_name}.yaml"
    suite_config = generated_dir / f"suite_{out_name}.yaml"

    base_cfg = _abs("configs/scheduling/base_optimization.yaml")

    suite = {
        "name": f"custom_tight_frequency_bounds__{out_name}",
        "baseline_id": "retained_default",
        "results_root": str(results_root),
        "output": {
            "summary_csv": str(suite_summary_csv),
            "summary_markdown": str(suite_summary_md),
            "summary_json": str(suite_summary_json),
        },
        "scenarios": [
            {
                "id": scenario_id,
                "name": scenario_id,
                "description": "Custom tight-bound run generated by helper script.",
                "overrides": {
                    "scenario": {
                        "id": scenario_id,
                        "name": scenario_id,
                        "description": "Uniform active/reactive load step across all PQ loads.",
                        "base_scale": float(args.base_scale),
                        "step_scale": float(args.step_scale),
                    },
                    "features": {"contingency_mode": "load_mismatch"},
                },
            }
        ],
        "runs": [
            {
                "id": "retained_default",
                "comparison_family": "tight_frequency_bounds_custom",
                "name": "Retained default bounds",
                "description": "Default retained bounds.",
                "base_config": str(base_cfg),
                "overrides": {
                    "solver": {"extra_kwargs": {"TimeLimit": 3600}},
                    "constraints": {
                        "use_input": True,
                        "use_output": True,
                        "use_nn": True,
                        "use_line": True,
                        "use_n1": False,
                        "use_n1_redispatch": False,
                        "use_ed": True,
                        "nn_mode": "milp",
                        "enforce_dispatch_output_link": True,
                    },
                    "bounds": {
                        "y_min": [-1.0, -0.8, -5.0, -5.0, -5.0, -5.0],
                        "y_max": [1.0, 0.8, 5.0, 5.0, 5.0, 5.0],
                    },
                },
            },
            {
                "id": case_id,
                "comparison_family": "tight_frequency_bounds_custom",
                "name": f"Custom tight bounds (|df|<={delta_f:.3g}, |RoCoF|<={rocof:.3g})",
                "description": "Custom retained run with user-specified frequency bounds.",
                "base_config": str(base_cfg),
                "overrides": {
                    "solver": {"extra_kwargs": {"TimeLimit": 3600}},
                    "constraints": {
                        "use_input": True,
                        "use_output": True,
                        "use_nn": True,
                        "use_line": True,
                        "use_n1": False,
                        "use_n1_redispatch": False,
                        "use_ed": True,
                        "nn_mode": "milp",
                        "enforce_dispatch_output_link": True,
                    },
                    "bounds": {
                        "y_min": [-rocof, -delta_f, -5.0, -5.0, -5.0, -5.0],
                        "y_max": [rocof, delta_f, 5.0, 5.0, 5.0, 5.0],
                    },
                },
            },
        ],
    }

    suite_config.write_text(yaml.safe_dump(suite, sort_keys=False), encoding="utf-8")

    default_summary = results_root / scenario_id / "retained_default" / f"retained_default__{scenario_id}_summary.json"
    custom_summary = results_root / scenario_id / case_id / f"{case_id}__{scenario_id}_summary.json"
    replay = {
        "tds": {
            "t_end": 20.0,
            "t_step": 0.01,
            "method": "backeuler",
            "no_tqdm": True,
            "criteria": 0,
        },
        "contingency": {
            "type": "load_step",
            "time": 1.0,
            "scale": float(args.step_scale),
        },
        "limits": {
            "frequency_hz": 50.0,
            "delta_f_hz": float(delta_f),
            "rocof_hz_per_s": float(rocof),
        },
        "output": {
            "directory": str(replay_outdir),
            "title": "",
            "panel_title": "",
            "plot_mode": "combined",
            "ibr_scale": 100.0,
            "ibr_unit": "MW",
        },
        "runs": [
            {"label": "Default bounds", "summary_json": str(default_summary), "linestyle": "-"},
            {"label": f"Custom (|df|<={delta_f:.3g}, |RoCoF|<={rocof:.3g})", "summary_json": str(custom_summary), "linestyle": "--"},
        ],
    }
    replay_config.write_text(yaml.safe_dump(replay, sort_keys=False), encoding="utf-8")

    py = sys.executable
    _run(
        [
            py,
            "scheduling/run_experiment_suite.py",
            "--suite",
            str(suite_config),
            "--log-tail-lines",
            str(int(args.log_tail_lines)),
        ]
    )
    if custom_summary.exists():
        payload = json.loads(custom_summary.read_text())
        status = str(payload.get("status", "")).lower()
        if not status.startswith("optimal") and not bool(args.allow_infeasible_replay):
            raise RuntimeError(
                "Custom run is not optimal; replay export aborted. "
                "Use --allow-infeasible-replay to override for debugging."
            )
    _run([py, "results/thesis_optimization_results/scripts/export_replay_trace_panel.py", "--config", str(replay_config)])

    print(f"[run_custom_tight_bound_trace] Suite config: {suite_config}")
    print(f"[run_custom_tight_bound_trace] Replay config: {replay_config}")
    print(f"[run_custom_tight_bound_trace] Output panel: {replay_outdir / 'replay_trace_panel.pdf'}")


if __name__ == "__main__":
    main()
